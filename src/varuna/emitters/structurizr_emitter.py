"""Generates valid, hierarchical Structurizr DSL (workspace.dsl) files across C1, C2, and C3 views with C4 module properties."""

from __future__ import annotations

import re
from pathlib import Path

from varuna.models.graph_schema import (
    AnalysisResult,
    ExternalBoundary,
    NodeKind,
)


def emit_structurizr_dsl(result: AnalysisResult, output_path: Path) -> Path:
    """Render an AnalysisResult into a complete Structurizr DSL (`workspace.dsl`) file."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    dsl_content = generate_structurizr_string(result)
    output_path.write_text(dsl_content, encoding="utf-8")
    return output_path


def generate_structurizr_string(result: AnalysisResult) -> str:
    sys_id = _safe_id(result.project_name) or "target_system"
    app_id = "core_app"
    langs_str = ", ".join(lang.value.title() for lang in result.languages_detected) or "Polyglot"

    # Separate C2 internal datastores/queues from C1 external systems
    c2_stores: list[ExternalBoundary] = []
    c1_externals: list[ExternalBoundary] = []
    for b in result.external_boundaries.values():
        if b.kind in (NodeKind.DATABASE, NodeKind.QUEUE):
            c2_stores.append(b)
        else:
            c1_externals.append(b)

    lines: list[str] = [
        "// Auto-generated by Project Varuna (AST + Centrality Pruning + Louvain Community Detection)",
        f'workspace "{_esc(result.project_name)}" "Automated C4 Architecture Model (Modularity Q={result.modularity_score:.2f}, Alignment={result.namespace_alignment_score:.0%})" {{',
        "  !identifiers hierarchical",
        "",
        "  model {",
        '    consumer = person "Developer / API Consumer" "Invokes CLI commands, HTTP endpoints, or public entrypoints"',
        "",
    ]

    # C1 External Systems
    for ext in c1_externals:
        lines.append(
            f'    {ext.id} = softwareSystem "{_esc(ext.name)}" "{_esc(ext.description)}" "External"'
        )
    if c1_externals:
        lines.append("")

    # Target System (C1)
    lines.extend(
        [
            f'    {sys_id} = softwareSystem "{_esc(result.project_name)}" "Automated C4 model (Modularity Q={result.modularity_score:.2f}, Alignment={result.namespace_alignment_score:.0%})" {{',
            f'      {app_id} = container "{_esc(result.project_name)} Application" "Primary application runtime containing Louvain-discovered C3 components" "{_esc(langs_str)}" {{',
        ]
    )

    # C3 Components inside core_app with C4 CodeNode metadata in properties
    for comp in result.components:
        lines.extend(
            [
                f'        {comp.id} = component "{_esc(comp.name)}" "{_esc(comp.description)}" "{_esc(comp.technology)}" {{',
                "          properties {",
                f'            "varuna.cohesion" "{comp.internal_cohesion:.0%}"',
                f'            "varuna.dominant_namespace" "{_esc(comp.dominant_namespace)}"',
                f'            "varuna.module_count" "{len(comp.node_ids)}"',
            ]
        )
        for nid in comp.node_ids:
            node = result.nodes.get(nid)
            if not node:
                continue
            mod_summary = (
                f"{node.relative_path} (in={node.in_degree}, out={node.out_degree}, PR={node.pagerank:.3f})"
            )
            lines.append(f'            "c4.module.{_esc(node.name)}" "{_esc(mod_summary)}"')
        lines.extend(
            [
                "          }",
                "        }",
            ]
        )

    lines.append("      }")  # end container core_app

    # C2 Datastores & Queues inside System
    for store in c2_stores:
        tag = "Database" if store.kind == NodeKind.DATABASE else "Queue"
        lines.append(
            f'      {store.id} = container "{_esc(store.name)}" "{_esc(store.description)}" "{_esc(store.technology)}" "{tag}"'
        )

    lines.append("    }")  # end softwareSystem
    lines.append("")

    # Relationships
    lines.append("    // --- Actor to Entrypoint Relationships ---")
    entry_comps = [c for c in result.components if c.is_entrypoint_component] or result.components[
        :1
    ]
    for ec in entry_comps:
        ep_labels = [ep.name for ep in ec.entrypoints[:2]]
        label = ", ".join(ep_labels) if ep_labels else "Invokes"
        lines.append(f'    consumer -> {sys_id}.{app_id}.{ec.id} "{_esc(label)}"')

    lines.append("")
    lines.append("    // --- C3 Inter-Component Dependencies (Louvain Aggregated) ---")
    for comp in result.components:
        for dst_comp_id, weight in sorted(comp.outbound_component_deps.items()):
            lines.append(
                f'    {sys_id}.{app_id}.{comp.id} -> {sys_id}.{app_id}.{dst_comp_id} "Depends on (w={weight:.1f})"'
            )

    lines.append("")
    lines.append("    // --- C3 Component to External & Datastore Boundaries ---")
    for comp in result.components:
        for b_id in comp.external_boundary_ids:
            boundary = result.external_boundaries.get(b_id)
            if not boundary:
                continue
            if boundary.kind in (NodeKind.DATABASE, NodeKind.QUEUE):
                lines.append(
                    f'    {sys_id}.{app_id}.{comp.id} -> {sys_id}.{boundary.id} "Reads/Writes" "{_esc(boundary.technology)}"'
                )
            else:
                lines.append(
                    f'    {sys_id}.{app_id}.{comp.id} -> {boundary.id} "Uses" "{_esc(boundary.technology)}"'
                )

    lines.append("  }")  # end model
    lines.append("")

    # Views (C1, C2, C3, and Styles)
    lines.extend(
        [
            "  views {",
            f'    systemContext {sys_id} "c1_context" {{',
            f'      title "C1 - System Context: {_esc(result.project_name)}"',
            "      include *",
            "      autoLayout",
            "    }",
            "",
            f'    container {sys_id} "c2_containers" {{',
            f'      title "C2 - Container View: {_esc(result.project_name)}"',
            "      include *",
            "      autoLayout",
            "    }",
            "",
            f'    component {sys_id}.{app_id} "c3_components" {{',
            f'      title "C3 - Louvain Components: {_esc(result.project_name)}"',
            "      include *",
            "      autoLayout",
            "    }",
            "",
            "    styles {",
            '      element "Person" {',
            "        shape Person",
            "        background #08427b",
            "        color #ffffff",
            "      }",
            '      element "Software System" {',
            "        background #1168bd",
            "        color #ffffff",
            "      }",
            '      element "External" {',
            "        background #999999",
            "        color #ffffff",
            "      }",
            '      element "Container" {',
            "        background #438dd5",
            "        color #ffffff",
            "      }",
            '      element "Component" {',
            "        background #85bbf0",
            "        color #000000",
            "      }",
            '      element "Database" {',
            "        shape Cylinder",
            "      }",
            '      element "Queue" {',
            "        shape Pipe",
            "      }",
            "    }",
            "  }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def _safe_id(raw: str) -> str:
    cleaned = re.sub(r"[^a-zA-Z0-9_]+", "_", raw).strip("_").lower()
    if cleaned and cleaned[0].isdigit():
        cleaned = f"n_{cleaned}"
    return cleaned


def _esc(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ").strip()
