"""Generates valid, hierarchical LikeC4 DSL (.c4) files across C1, C2, C3, and C4 zoom levels."""

from __future__ import annotations

import re
from pathlib import Path

from varuna.models.graph_schema import (
    AnalysisResult,
    ExternalBoundary,
    NodeKind,
)


def emit_likec4_dsl(result: AnalysisResult, output_path: Path) -> Path:
    """Render an AnalysisResult into a complete LikeC4 (`architecture.c4`) file."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    dsl_content = generate_likec4_string(result)
    output_path.write_text(dsl_content, encoding="utf-8")
    return output_path


def generate_likec4_string(result: AnalysisResult) -> str:
    sys_id = _safe_id(result.project_name) or "target_system"
    app_id = "core_app"
    langs_str = ", ".join(lang.value.title() for lang in result.languages_detected) or "Polyglot"

    # Separate C2 internal datastores/queues from C1 external systems
    c2_stores: list[ExternalBoundary] = []
    c1_externals: list[ExternalBoundary] = []
    for b in result.external_boundaries.values():
        if b.kind in (NodeKind.DATABASE, NodeKind.QUEUE):
            c2_stores.append(b)
        else:
            c1_externals.append(b)

    lines: list[str] = [
        "// Auto-generated by Project Varuna (AST + Centrality Pruning + Louvain Community Detection)",
        "specification {",
        "  element actor {",
        "    style {",
        "      shape person",
        "      color green",
        "    }",
        "  }",
        "  element system",
        "  element container",
        "  element component",
        "  element module {",
        "    style {",
        "      color slate",
        "    }",
        "  }",
        "  element database {",
        "    style {",
        "      shape cylinder",
        "      color indigo",
        "    }",
        "  }",
        "  element queue {",
        "    style {",
        "      shape queue",
        "      color amber",
        "    }",
        "  }",
        "  element external_system {",
        "    style {",
        "      color muted",
        "    }",
        "  }",
        "}",
        "",
        "model {",
        "  consumer = actor 'Developer / API Consumer' {",
        "    description 'Invokes CLI commands, HTTP endpoints, or public entrypoints'",
        "  }",
        "",
    ]

    # C1 External Systems
    for ext in c1_externals:
        lines.extend(
            [
                f"  {ext.id} = external_system '{_esc(ext.name)}' {{",
                f"    technology '{_esc(ext.technology)}'",
                f"    description '{_esc(ext.description)}'",
                "  }",
            ]
        )
    if c1_externals:
        lines.append("")

    # Target System (C1)
    lines.extend(
        [
            f"  {sys_id} = system '{_esc(result.project_name)}' {{",
            f"    description 'Automated C4 model (Modularity Q={result.modularity_score:.2f}, Alignment={result.namespace_alignment_score:.0%})'",
            "",
            f"    {app_id} = container '{_esc(result.project_name)} Application' {{",
            f"      technology '{_esc(langs_str)}'",
            "      description 'Primary application runtime containing Louvain-discovered C3 components'",
            "",
        ]
    )

    # Map each CodeNode id to its full qualified LikeC4 path for C4 module edges
    node_fqn: dict[str, str] = {}

    # C3 Components inside core_app
    for comp in result.components:
        lines.extend(
            [
                f"      {comp.id} = component '{_esc(comp.name)}' {{",
                f"        technology '{_esc(comp.technology)}'",
                f"        description '{_esc(comp.description)}'",
            ]
        )
        # Nested C4 Code Modules
        for nid in comp.node_ids:
            node = result.nodes.get(nid)
            if not node:
                continue
            mod_id = _safe_id(f"mod_{node.name}_{nid.replace('.', '_')}")
            fqn = f"{sys_id}.{app_id}.{comp.id}.{mod_id}"
            node_fqn[nid] = fqn
            mod_desc = (
                node.docstring
                or f"{node.relative_path} (in={node.in_degree}, out={node.out_degree}, PR={node.pagerank:.3f})"
            )
            lines.extend(
                [
                    f"        {mod_id} = module '{_esc(node.name)}' {{",
                    f"          technology '{_esc(node.relative_path)}'",
                    f"          description '{_esc(mod_desc)}'",
                    "        }",
                ]
            )
        lines.append("      }")
        lines.append("")

    lines.append("    }")  # end container core_app

    # C2 Datastores & Queues inside System
    for store in c2_stores:
        elem_kind = "database" if store.kind == NodeKind.DATABASE else "queue"
        lines.extend(
            [
                f"    {store.id} = {elem_kind} '{_esc(store.name)}' {{",
                f"      technology '{_esc(store.technology)}'",
                f"      description '{_esc(store.description)}'",
                "    }",
            ]
        )

    lines.append("  }")  # end system
    lines.append("")

    # Relationships
    lines.append("  // --- Actor to Entrypoint Relationships ---")
    entry_comps = [c for c in result.components if c.is_entrypoint_component] or result.components[
        :1
    ]
    for ec in entry_comps:
        ep_labels = [ep.name for ep in ec.entrypoints[:2]]
        label = ", ".join(ep_labels) if ep_labels else "Invokes"
        lines.append(f"  consumer -> {sys_id}.{app_id}.{ec.id} '{_esc(label)}'")

    lines.append("")
    lines.append("  // --- C3 Inter-Component Dependencies (Louvain Aggregated) ---")
    for comp in result.components:
        for dst_comp_id, weight in sorted(comp.outbound_component_deps.items()):
            lines.append(
                f"  {sys_id}.{app_id}.{comp.id} -> {sys_id}.{app_id}.{dst_comp_id} 'Depends on (w={weight:.1f})'"
            )

    lines.append("")
    lines.append("  // --- C3 Component to External & Datastore Boundaries ---")
    for comp in result.components:
        for b_id in comp.external_boundary_ids:
            boundary = result.external_boundaries.get(b_id)
            if not boundary:
                continue
            if boundary.kind in (NodeKind.DATABASE, NodeKind.QUEUE):
                lines.append(
                    f"  {sys_id}.{app_id}.{comp.id} -> {sys_id}.{boundary.id} 'Reads/Writes ({_esc(boundary.technology)})'"
                )
            else:
                lines.append(
                    f"  {sys_id}.{app_id}.{comp.id} -> {boundary.id} 'Uses ({_esc(boundary.technology)})'"
                )

    lines.append("")
    lines.append("  // --- C4 Module-Level AST Dependencies ---")
    for edge in result.edges:
        src_fqn = node_fqn.get(edge.source)
        dst_fqn = node_fqn.get(edge.target)
        if src_fqn and dst_fqn and src_fqn != dst_fqn:
            lines.append(f"  {src_fqn} -> {dst_fqn} '{_esc(edge.kind.value)}'")

    lines.append("}")  # end model
    lines.append("")

    # Views (C1, C2, C3, and C4 per component)
    lines.extend(
        [
            "views {",
            "  view index {",
            f"    title 'C1 - System Context: {_esc(result.project_name)}'",
            "    include *",
            "  }",
            "",
            f"  view c2_containers of {sys_id} {{",
            f"    title 'C2 - Container View: {_esc(result.project_name)}'",
            "    include *",
            "    include consumer",
        ]
    )
    for ext in c1_externals:
        lines.append(f"    include {ext.id}")
    lines.extend(
        [
            "  }",
            "",
            f"  view c3_components of {sys_id}.{app_id} {{",
            f"    title 'C3 - Louvain Components: {_esc(result.project_name)}'",
            "    include *",
            "    include consumer",
        ]
    )
    for b in result.external_boundaries.values():
        if b.kind in (NodeKind.DATABASE, NodeKind.QUEUE):
            lines.append(f"    include {sys_id}.{b.id}")
        else:
            lines.append(f"    include {b.id}")
    lines.append("  }")

    for comp in result.components:
        lines.extend(
            [
                "",
                f"  view c4_{comp.id} of {sys_id}.{app_id}.{comp.id} {{",
                f"    title 'C4 - Code Modules: {_esc(comp.name)}'",
                "    include *",
                "  }",
            ]
        )

    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def _safe_id(raw: str) -> str:
    cleaned = re.sub(r"[^a-zA-Z0-9_]+", "_", raw).strip("_").lower()
    if cleaned and cleaned[0].isdigit():
        cleaned = f"n_{cleaned}"
    return cleaned


def _esc(text: str) -> str:
    return text.replace("'", "\\'").replace("\n", " ").strip()
